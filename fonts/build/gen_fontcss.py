"""Write src/b-layer/58-alto-fonts.css: embedded web fonts shipped with Plectics Alto.

    python -I fonts/build/gen_fontcss.py

Fonts:
  Alto Garamond Condensed Regular, Italic: SIL OFL 1.1 derivative of EB Garamond
    (fonts/web/AltoGaramondCondensed-*.woff2; notices in the name table).
  PLX Caps = Nimbus Sans Regular, Bold by (URW)++ (urw-base35, AGPL-3.0;
    COPYING and LICENSE in fonts/nimbus/). Subset, otherwise unmodified.
  Archivo (interface face), weights 100-900 at width 100: SIL OFL 1.1, by The
    Archivo Project Authors (fonts/archivo/OFL-Archivo.txt).
Subsets: Latin-1, Latin Extended-A, punctuation, arrows, minus (and a few
marks for the caps face). Re-make the subsets with fonts/build/make_web_subsets.py.
An installed copy of each face is preferred (local()); the embedded one is
the fallback.
"""
import base64, pathlib

HERE = pathlib.Path(__file__).resolve().parents[2]
W = HERE / "fonts" / "web"
OUT = HERE / "src" / "b-layer" / "58-alto-fonts.css"


def data(fn):
    return base64.b64encode((W / f"{fn}.woff2").read_bytes()).decode()


def face(family, style, weight, locals_, fn):
    src = ", ".join(f'local("{l}")' for l in locals_)
    return (f'@font-face {{ font-family: "{family}"; font-style: {style}; font-weight: {weight}; font-display: swap;\n'
            f'  src: {src},\n'
            f'       url("data:font/woff2;base64,{data(fn)}") format("woff2"); }}')


css = [
    "/* ==========================================================================",
    "   PLECTICS ALTO · 58 · SHIPPED FONTS — generated by fonts/build/gen_fontcss.py",
    "   Alto Garamond Condensed: EB Garamond (© 2017 The EB Garamond Project Authors)",
    "   condensed to 80 % with weight compensation. SIL Open Font License 1.1.",
    "   PLX Caps: Nimbus Sans, © (URW)++ Design & Development, AGPL-3.0 (urw-base35),",
    "   subset. Archivo: © 2020 The Archivo Project Authors, SIL OFL 1.1, subset at",
    "   width 100. The theme itself is GPL-3.0; see NOTICE.md.",
    "   ========================================================================== */",
    "",
    face("Alto Garamond Condensed", "normal", 400,
         ["Alto Garamond Condensed", "AltoGaramondCondensed-Regular"], "AltoGaramondCondensed-Regular"),
    face("Alto Garamond Condensed", "italic", 400,
         ["Alto Garamond Condensed Italic", "AltoGaramondCondensed-Italic"], "AltoGaramondCondensed-Italic"),
    face("PLX Caps", "normal", "100 549",
         ["Nimbus Sans L Regular", "NimbusSanL-Reg", "Nimbus Sans Regular", "NimbusSans-Regular"], "NimbusSans-Regular"),
    face("PLX Caps", "normal", "550 900",
         ["Nimbus Sans L Bold", "NimbusSanL-Bol", "Nimbus Sans Bold", "NimbusSans-Bold"], "NimbusSans-Bold"),
    face("Archivo", "normal", "100 900", [], "Archivo"),
    "",
    "/* Title face: Alto Garamond Condensed is the default. */",
    'body { --plx-display: "Alto Garamond Condensed", "EB Garamond", Georgia, serif; --plx-display-weight: 400; }',
    'body.plx-display-apple { --plx-display: "Apple Garamond", "EB Garamond", Georgia, serif; --plx-display-weight: 400; }',
    "",
]
OUT.write_text("\n".join(css), encoding="utf-8")
print(OUT.name, OUT.stat().st_size // 1024, "KB")
